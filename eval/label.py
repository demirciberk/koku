"""Turn eval/queries.jsonl constraints into relevance labels (eval/qrels.jsonl).

A perfume is relevant to a query when it satisfies every constraint:
  lead_accords every accord is one of the perfume's two strongest accords ("dominant", "heavy on")
  all_accords  every accord is in the perfume's top-5 accords
  any_accords  at least one is
  no_accords   none is
  notes        every note pattern matches some note (whole-word match)
  any_notes    at least one does
  no_notes     none does
  gender       perfume gender is one of these
Only perfumes with >= MIN_VOTES votes form the search corpus (well-known, cleaner data).

Run: python eval/label.py
"""
import json
import re
from functools import cache

MIN_VOTES = 100
MIN_REL, MAX_REL = 3, 800  # outside this range a query is too narrow or too vague to measure


@cache
def note_re(pattern: str) -> re.Pattern:
    # hyphen counts as part of a word so "lily" does not match "lily-of-the-valley"
    return re.compile(rf"(?<![\w-]){re.escape(pattern)}(?![\w-])")


def has_note(notes: list[str], pattern: str) -> bool:
    rx = note_re(pattern)
    return any(rx.search(n) for n in notes)


def relevant(q: dict, p: dict) -> bool:
    acc, notes = set(p["accords"]), p["top"] + p["middle"] + p["base"]
    lead = set(p["accords"][:2])
    return (
        all(a in lead for a in q.get("lead_accords", []))
        and all(a in acc for a in q.get("all_accords", []))
        and (not q.get("any_accords") or any(a in acc for a in q["any_accords"]))
        and not any(a in acc for a in q.get("no_accords", []))
        and all(has_note(notes, n) for n in q.get("notes", []))
        and (not q.get("any_notes") or any(has_note(notes, n) for n in q["any_notes"]))
        and not any(has_note(notes, n) for n in q.get("no_notes", []))
        and (not q.get("gender") or p["gender"] in q["gender"])
    )


def load(path: str) -> list[dict]:
    with open(path, encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def corpus() -> list[dict]:
    return [p for p in load("data/perfumes.jsonl") if p["votes"] >= MIN_VOTES]


def selftest() -> None:
    p = {"accords": ["woody", "citrus"], "top": ["lily-of-the-valley"], "middle": ["madagascar vanilla"], "base": [], "gender": "men"}
    assert relevant({"all_accords": ["woody"], "notes": ["vanilla"], "gender": ["men"]}, p)
    assert not relevant({"notes": ["lily"]}, p), "hyphenated note must not match its prefix"
    assert not relevant({"no_accords": ["citrus"]}, p)
    assert not relevant({"any_accords": ["sweet", "floral"]}, p)
    assert not relevant({"gender": ["women"]}, p)
    assert relevant({"lead_accords": ["citrus"]}, p)
    assert not relevant({"lead_accords": ["floral"]}, {**p, "accords": ["woody", "citrus", "floral"]}), "3rd accord is not lead"


if __name__ == "__main__":
    selftest()
    docs = corpus()
    queries = load("eval/queries.jsonl")
    assert len({q["id"] for q in queries}) == len(queries), "duplicate query ids"
    out, bad = [], []
    for q in queries:
        rel = [p["id"] for p in docs if relevant(q, p)]
        out.append({"id": q["id"], "relevant": rel})
        if not MIN_REL <= len(rel) <= MAX_REL:
            bad.append((q["id"], len(rel), q["query"]))
    with open("eval/qrels.jsonl", "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r) + "\n")
    sizes = sorted(len(r["relevant"]) for r in out)
    print(f"corpus={len(docs)} queries={len(queries)} relevant: min={sizes[0]} median={sizes[len(sizes)//2]} max={sizes[-1]}")
    for b in bad:
        print("OUT OF RANGE", *b)

    # Human review sheet: query, its constraints, match count, the 3 best-known matches.
    by_id = {p["id"]: p for p in docs}
    keys = ("lead_accords", "all_accords", "any_accords", "no_accords", "notes", "any_notes", "no_notes", "gender")
    with open("eval/review.md", "w", encoding="utf-8") as f:
        f.write("# Eval set review\n\nGenerated by `python eval/label.py`. Edit `eval/queries.jsonl`, not this file.\n\n")
        f.write("| id | query | constraints | matches | best-known matches |\n|---|---|---|---|---|\n")
        for q, r in zip(queries, out):
            cons = "; ".join(f"{k}: {', '.join(q[k])}" for k in keys if q.get(k))
            top3 = sorted((by_id[i] for i in r["relevant"]), key=lambda p: -p["votes"])[:3]
            names = ", ".join(f"{p['brand']} {p['name']}" for p in top3)
            f.write(f"| {q['id']} | {q['query']} | {cons} | {len(r['relevant'])} | {names} |\n")
